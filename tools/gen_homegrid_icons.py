#!/usr/bin/env python3
"""Generate apps/homegrid_icons.h: six 24x24 one-bit icons for the Zen X-Fi
icon home page (apps/homegrid.c).  Each icon is 24 rows of a 32-bit word,
bit 23 is the leftmost pixel.  The firmware draws every set pixel as a 2x2
square in the theme's colours, so the icons follow the active theme.

Usage: tools/gen_homegrid_icons.py [--preview] > apps/homegrid_icons.h
"""
import math
import sys

N = 24


def blank():
    return [[0] * N for _ in range(N)]


def put(g, x, y):
    if 0 <= x < N and 0 <= y < N:
        g[y][x] = 1


def line(g, x0, y0, x1, y1):
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx = 1 if x0 < x1 else -1
    sy = 1 if y0 < y1 else -1
    err = dx + dy
    while True:
        put(g, x0, y0)
        if x0 == x1 and y0 == y1:
            break
        e2 = 2 * err
        if e2 >= dy:
            err += dy
            x0 += sx
        if e2 <= dx:
            err += dx
            y0 += sy


def rect(g, x0, y0, x1, y1):
    line(g, x0, y0, x1, y0)
    line(g, x1, y0, x1, y1)
    line(g, x1, y1, x0, y1)
    line(g, x0, y1, x0, y0)


def poly(g, pts, close=False):
    for a, b in zip(pts, pts[1:]):
        line(g, a[0], a[1], b[0], b[1])
    if close:
        line(g, pts[-1][0], pts[-1][1], pts[0][0], pts[0][1])


def fill_poly(g, pts):
    """Even-odd scanline fill, sampled at pixel centres."""
    n = len(pts)
    for y in range(N):
        yc = y + 0.5
        xs = []
        for i in range(n):
            (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % n]
            if (y0 <= yc < y1) or (y1 <= yc < y0):
                xs.append(x0 + (yc - y0) * (x1 - x0) / (y1 - y0))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            for x in range(int(math.ceil(a - 0.5)), int(math.floor(b - 0.5)) + 1):
                put(g, x, y)


def circle(g, cx, cy, r):
    x, y, err = r, 0, 1 - r
    while x >= y:
        for px, py in ((x, y), (y, x), (-y, x), (-x, y),
                       (-x, -y), (-y, -x), (y, -x), (x, -y)):
            put(g, cx + px, cy + py)
        y += 1
        if err < 0:
            err += 2 * y + 1
        else:
            x -= 1
            err += 2 * (y - x) + 1


def icon_audiobooks():
    g = blank()
    rect(g, 2, 4, 11, 19)
    rect(g, 12, 4, 21, 19)
    for y in (8, 11, 14):
        line(g, 4, y, 9, y)
        line(g, 14, y, 19, y)
    return g


def icon_music():
    g = blank()
    circle(g, 6, 18, 3)
    circle(g, 17, 16, 3)
    line(g, 9, 18, 9, 4)
    line(g, 20, 16, 20, 2)
    line(g, 9, 4, 20, 2)
    line(g, 9, 6, 20, 4)
    return g


def icon_podcasts():
    g = blank()
    rect(g, 9, 2, 14, 12)
    line(g, 10, 1, 13, 1)
    line(g, 10, 13, 13, 13)
    poly(g, [(5, 9), (5, 12), (7, 16), (11, 18), (12, 18), (16, 16),
             (18, 12), (18, 9)])
    line(g, 11, 18, 11, 21)
    line(g, 12, 18, 12, 21)
    line(g, 8, 22, 15, 22)
    return g


def icon_ambience():
    g = blank()
    for base in (6, 12, 18):
        for x in range(1, 23):
            put(g, x, base + round(2.2 * math.sin((x - 1) * math.pi / 5.5)))
    return g


def icon_mode():
    g = blank()
    line(g, 2, 8, 20, 8)
    poly(g, [(16, 4), (20, 8), (16, 12)])
    line(g, 3, 16, 21, 16)
    poly(g, [(7, 12), (3, 16), (7, 20)])
    return g


def icon_shortcuts():
    g = blank()
    fill_poly(g, [(14, 0), (4, 13), (11, 13), (8, 24), (20, 9), (13, 9)])
    return g


ICONS = [
    ("audiobooks", icon_audiobooks),
    ("music", icon_music),
    ("podcasts", icon_podcasts),
    ("ambience", icon_ambience),
    ("mode", icon_mode),
    ("shortcuts", icon_shortcuts),
]


def preview():
    for name, fn in ICONS:
        print(name)
        for row in fn():
            print("".join("#" if v else "." for v in row))
        print()


def emit():
    out = []
    out.append("/* Generated by tools/gen_homegrid_icons.py - do not edit. */")
    out.append("#define HOMEGRID_ICON_SIZE %d" % N)
    out.append("static const unsigned long homegrid_icons[%d][%d] = {"
               % (len(ICONS), N))
    for name, fn in ICONS:
        rows = []
        for row in fn():
            v = 0
            for x, bit in enumerate(row):
                if bit:
                    v |= 1 << (N - 1 - x)
            rows.append("0x%06lx" % v)
        out.append("    /* %s */ {" % name)
        for i in range(0, N, 6):
            out.append("        " + ", ".join(rows[i:i + 6]) + ",")
        out.append("    },")
    out.append("};")
    print("\n".join(out))


if __name__ == "__main__":
    if "--preview" in sys.argv:
        preview()
    else:
        emit()
